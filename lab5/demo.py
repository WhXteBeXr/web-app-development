"""Длинная новость для проверки карточки и страницы полного текста."""

from news.models import Category, News

category, _ = Category.objects.get_or_create(title="Учебные материалы")
text = (
    "Шаблон Django отделяет оформление страницы от получения данных. "
    "Контроллер выбирает новости из базы и передает их в контекст. "
    "HTML-шаблон обращается к полям объектов, выводит категорию и форматирует дату. "
    "Bootstrap помогает расположить изображение и текст внутри карточки, "
    "а на небольшом экране эти элементы переходят в одну колонку.\n\n"
    "В списке отображаются первые пятьдесят слов новости. "
    "Кнопка «Подробнее» открывает отдельную страницу с полным содержанием. "
    "При отсутствии фотографии выводится локальное изображение-заглушка. "
    "Переносы строк остаются видимыми, а введенные HTML-теги отображаются как текст. "
    "Нумерация карточек начинается с единицы, цвета заголовков чередуются, "
    "и вверху страницы указано время ее формирования. "
    "Все эти действия выполняются при рендеринге одного общего проекта."
)
item, created = News.objects.get_or_create(
    title="Как устроен шаблон новостной ленты",
    defaults={"content": text, "category": category, "is_published": True},
)
print("Создана" if created else "Уже существует", item.title)
print("Количество слов:", len(item.content.split()))
print("Полная новость:", f"/news/{item.pk}/")
print("Метод модели:", item.get_publication_status())
